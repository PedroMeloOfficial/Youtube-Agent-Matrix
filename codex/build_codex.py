"""
Generate the OpenAI Codex version of the plugin from the Claude Code sources.

The Claude Code files are the single source of truth and are never modified here:
  agents/*.md            -> codex/agents/<name>.toml        (Codex custom agents)
  skills/*/SKILL.md      -> codex/skills/<name>/SKILL.md    (same text + a Codex preamble)
  commands/yt.md         -> codex/skills/yt/SKILL.md        (invoked as `$yt <verb>`)
  .claude-plugin/plugin.json -> .codex-plugin/plugin.json   (same name, version, description)
  (fixed)                -> .agents/plugins/marketplace.json

Never edit a generated file by hand: edit the Claude source and run this again.
`--check` exits 1 when a generated file is missing or stale (used by the tests and the
release checklist).

Usage:
    python3 codex/build_codex.py            # write
    python3 codex/build_codex.py --check    # verify, write nothing
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLACEHOLDER = "__PLUGIN_ROOT__"
GENERATED = "GENERATED by codex/build_codex.py from {src}. Do not edit: edit the source and rebuild."

# Claude model alias -> Codex reasoning effort. No Codex model is pinned: the creator's
# default model is used, so the port never breaks when OpenAI renames a model.
EFFORT = {"opus": "high", "sonnet": "medium", "haiku": "low"}

FIND_ROOT = ("find ~/.codex ~/.agents -name plugin.json -path '*.codex-plugin*' 2>/dev/null "
             "| xargs grep -l '\"youtube-agent-matrix\"' | head -1")

TOOL_MAP = """\
- **Claude tool names → yours.** `Read`, `Write`, `Edit`, `Glob`, `Grep` → your file tools and the
  shell. `Bash` → the shell. `WebSearch`, `WebFetch` → your web search / fetch; if web access is off,
  say so once and follow the fallback these instructions give for missing live data — never invent
  a number. "Task tool" / "subagent" / "delegate to `<x>-agent`" → spawn the Codex custom agent of
  that exact name (installed by `codex/install.sh`); if you cannot spawn agents, run that agent's
  instructions inline (they are in `<plugin root>/agents/<x>-agent.md`) and say you did.
- **`/yt <verb>`** in these instructions is typed as **`$yt <verb>`** in Codex.
- **`workspace/`** stays relative to the folder the creator launched Codex from, exactly as written."""


def split_frontmatter(text: str, src: str) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        raise SystemExit(f"{src}: no YAML frontmatter")
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                v = v[1:-1]
            meta[k.strip()] = v
    return meta, m.group(2)


def codexify(text: str) -> str:
    """Claude-only spellings that would mislead Codex; meaning is unchanged."""
    return text.replace("youtube-agent-matrix:", "")


def toml_str(s: str) -> str:
    # a JSON string is a valid TOML basic string and a valid YAML double-quoted scalar
    return json.dumps(s, ensure_ascii=False)


def toml_multiline(s: str) -> str:
    if "'''" not in s:
        return "'''\n" + s + "'''"
    esc = s.replace("\\", "\\\\").replace('"', '\\"')
    return '"""\n' + esc + '"""'


def agent_preamble(meta: dict) -> str:
    return f"""\
## Running in OpenAI Codex

These instructions were written for Claude Code and are shared unchanged with Codex. Read them with
these translations:

- **Plugin root:** `{PLACEHOLDER}` (if that still reads as a placeholder, find it with
  `{FIND_ROOT}` — the root is the folder that holds `.codex-plugin/`). Every path starting with
  `references/`, `templates/`, `execution/`, `agents/` or `skills/` is relative to it. Before the
  first script, run `export CLAUDE_PLUGIN_ROOT="<plugin root>"` in the same shell command, so
  `${{CLAUDE_PLUGIN_ROOT}}` in the commands below resolves.
{TOOL_MAP}
- **Scope.** In Claude Code this agent may use only: {meta.get('tools', 'all tools')}. Keep to the same
  scope here, and write only the files these instructions say you own.

---

"""


def skill_preamble(name: str) -> str:
    return f"""\
## Running in OpenAI Codex

These instructions were written for Claude Code and are shared unchanged with Codex. Read them with
these translations:

- **Plugin root:** this file is `<plugin root>/codex/skills/{name}/SKILL.md`, so the plugin root is
  three folders up from it (or find it with `{FIND_ROOT}`). Every path starting with `references/`,
  `templates/`, `execution/`, `agents/` or `skills/` is relative to it. Before the first script, run
  `export CLAUDE_PLUGIN_ROOT="<plugin root>"` in the same shell command, so `${{CLAUDE_PLUGIN_ROOT}}`
  resolves.
{TOOL_MAP}
- **Gates still hold.** Every approval gate and "wait for yes" in these instructions applies in Codex
  exactly as written — stop and ask in the chat.

---

"""


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}

    # agents
    for src in sorted((ROOT / "agents").glob("*.md")):
        meta, body = split_frontmatter(src.read_text(encoding="utf-8"), src.name)
        name = meta.get("name") or src.stem
        lines = [f"# {GENERATED.format(src='agents/' + src.name)}",
                 f"name = {toml_str(name)}",
                 f"description = {toml_str(meta.get('description', ''))}"]
        effort = EFFORT.get(meta.get("model", "").lower())
        if effort:
            lines.append(f"model_reasoning_effort = {toml_str(effort)}")
        instr = agent_preamble(meta) + codexify(body).lstrip("\n")
        if not instr.endswith("\n"):
            instr += "\n"
        lines.append("developer_instructions = " + toml_multiline(instr))
        out[ROOT / "codex" / "agents" / f"{name}.toml"] = "\n".join(lines) + "\n"

    # skills
    for src in sorted((ROOT / "skills").glob("*/SKILL.md")):
        meta, body = split_frontmatter(src.read_text(encoding="utf-8"), str(src))
        name = meta.get("name") or src.parent.name
        rel = src.relative_to(ROOT).as_posix()
        text = (f"---\nname: {name}\ndescription: {toml_str(meta.get('description', ''))}\n---\n\n"
                f"<!-- {GENERATED.format(src=rel)} -->\n\n"
                + skill_preamble(name) + codexify(body).lstrip("\n"))
        out[ROOT / "codex" / "skills" / name / "SKILL.md"] = text

    # /yt command -> $yt skill
    meta, body = split_frontmatter((ROOT / "commands" / "yt.md").read_text(encoding="utf-8"), "commands/yt.md")
    body = codexify(body)
    body = body.replace("Load the `orchestrator` skill", "Load the `orchestrator` skill (`$orchestrator`)")
    body = body.replace("$ARGUMENTS", "the words the creator typed after `$yt` (none → empty)")
    desc = (meta.get("description", "") + ", plus the video editor. Type `$yt <verb>`, for example "
            "`$yt setup`, `$yt script` or `$yt edit`.")
    out[ROOT / "codex" / "skills" / "yt" / "SKILL.md"] = (
        f"---\nname: yt\ndescription: {toml_str(desc)}\n---\n\n"
        f"<!-- {GENERATED.format(src='commands/yt.md')} -->\n\n"
        + skill_preamble("yt") + body.lstrip("\n"))

    # manifests
    claude = json.loads((ROOT / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
    repo = "https://github.com/PedroMeloOfficial/Youtube-Agent-Matrix"
    manifest = {
        "name": claude["name"],
        "version": claude["version"],
        "description": claude["description"].replace("for Claude Code", "for Claude Code and OpenAI Codex"),
        "author": {"name": "Pedro Melo", "url": "https://github.com/PedroMeloOfficial"},
        "homepage": repo,
        "repository": repo,
        "license": claude.get("license", "MIT"),
        "keywords": claude.get("keywords", []),
        "skills": "./codex/skills/",
        "interface": {
            "displayName": "YouTube Agent Matrix",
            "shortDescription": "YouTube pre-production with 24 agents, plus a video editor for Final Cut Pro.",
            "developerName": "Pedro Melo",
            "category": "Productivity",
            "websiteURL": repo,
            "defaultPrompt": ["$yt setup", "$yt script", "$yt edit"],
        },
    }
    out[ROOT / ".codex-plugin" / "plugin.json"] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    market = {
        "name": claude["name"],
        "interface": {"displayName": "YouTube Agent Matrix"},
        "plugins": [{
            "name": claude["name"],
            "source": {"source": "local", "path": "./"},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
            "category": "Productivity",
        }],
    }
    out[ROOT / ".agents" / "plugins" / "marketplace.json"] = json.dumps(market, indent=2) + "\n"
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate the Codex version from the Claude sources.")
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if anything is stale")
    a = ap.parse_args()
    files = build()
    expected_dirs = {ROOT / "codex" / "agents", ROOT / "codex" / "skills"}
    stale = [p for p, txt in files.items() if not p.exists() or p.read_text(encoding="utf-8") != txt]
    orphans = [p for d in expected_dirs if d.exists() for p in d.rglob("*")
               if p.is_file() and p not in files]
    if a.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        for p in orphans:
            print(f"orphan (source removed?): {p.relative_to(ROOT)}")
        if stale or orphans:
            print("Run: python3 codex/build_codex.py")
            sys.exit(1)
        print(f"codex: {len(files)} generated files up to date")
        return
    for p in orphans:
        p.unlink()
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    print(f"codex: {len(stale)} written, {len(orphans)} removed, {len(files)} total")


if __name__ == "__main__":
    main()
